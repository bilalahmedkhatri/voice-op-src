const fs = require('node:fs');
const path = require('node:path');
const Module = require('node:module');
const assert = require('node:assert/strict');
const ts = require('typescript');
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const filename = path.resolve('app/components/workspace/WorkspacePageHeader.tsx');
const compiled = ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { jsx: ts.JsxEmit.ReactJSX, module: ts.ModuleKind.CommonJS } }).outputText;
const componentModule = new Module(filename, module);
componentModule.paths = Module._nodeModulePaths(path.dirname(filename));
const originalRequire = componentModule.require.bind(componentModule);
componentModule.require = name => name === 'next/navigation' ? { usePathname: () => '/settings' }
  : name === './WorkspaceTitleContext' ? { WorkspaceTitleContext: React.createContext(null) } : originalRequire(name);
componentModule._compile(compiled, filename);
const Header = componentModule.exports.default;
const render = props => renderToStaticMarkup(React.createElement(Header, props));
const actions = render({ actions: React.createElement('button', null, 'Refresh') });
assert.ok(actions.includes('<button>Refresh</button>'));
assert.ok(!actions.includes('<h1'));
assert.ok(actions.includes('ml-auto'));
const description = render({ description: 'Optional description' });
assert.ok(description.includes('Optional description'));
assert.ok(!description.includes('<h1'));
assert.equal(render({}), '');
const title = render({ title: 'Saved Templates' });
assert.ok(title.includes('<h1') && title.includes('Saved Templates'));
assert.ok(render({ title: 0 }).includes('>0</span>'));
console.log('PASS: actions-only, description-only, empty component, normal title and numeric zero title');
